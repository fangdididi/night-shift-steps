import os
import subprocess
import sys
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import stepcheck as sc  # noqa: E402


def codes(text, glossary=None):
    return {f["code"] for f in sc.lint(text, glossary)["findings"]}


class ParseTests(unittest.TestCase):
    def test_kinds(self):
        items = sc.parse("Intro line.\n1. Open the lid.\nResult: The lid is open.\nWARNING: Hot parts can burn you.\n2) Close it.")
        self.assertEqual([i["kind"] for i in items], ["desc", "step", "result", "safety", "step"])

    def test_code_blocks_skipped(self):
        items = sc.parse("1. Run the command.\n```\n2. not a step\n```\n")
        self.assertEqual(len([i for i in items if i["kind"] == "step"]), 1)

    def test_language_detection(self):
        self.assertEqual(sc.lang_of("1. 打开存储页面。"), "zh")
        self.assertEqual(sc.lang_of("1. Open the storage page."), "en")


class StepRules(unittest.TestCase):
    def test_clean_step_ready(self):
        self.assertEqual(sc.lint("1. Open the storage page.\n2. Select Disk 2.")["verdict"], "READY")

    def test_long(self):
        step = "1. " + " ".join(["word"] * 22) + "."
        self.assertIn("LONG", codes(step))

    def test_stacked_then(self):
        self.assertIn("STACKED", codes("1. Open the page, then select Disk 2."))

    def test_stacked_two_imperatives(self):
        self.assertIn("STACKED", codes("1. Open the page. Select Disk 2."))

    def test_passive(self):
        self.assertIn("HIDDEN-ACTOR", codes("1. The key is generated by the tool."))

    def test_open_not_passive(self):
        self.assertNotIn("HIDDEN-ACTOR", codes("1. Wait until the valve is open."))

    def test_hedge(self):
        self.assertIn("HEDGE", codes("1. You should wait 5 minutes."))

    def test_vague(self):
        self.assertIn("VAGUE", codes("1. Make sure the cable is in."))

    def test_condition_last(self):
        self.assertIn("CONDITION-LAST", codes("1. Close the ticket if the alert stops."))

    def test_condition_first_ok(self):
        self.assertNotIn("CONDITION-LAST", codes("1. If the alert stops, close the ticket."))

    def test_inline_code_one_word(self):
        self.assertNotIn("LONG", codes("1. Type `kubectl rollout status deploy/api --namespace production --timeout 120s --watch true`."))

    def test_glossary_drift(self):
        self.assertIn("DRIFT", codes("1. Remove the caddy.", {"tray": ["caddy"]}))


class SafetyRules(unittest.TestCase):
    def test_hazard_without_warning_unsafe(self):
        rep = sc.lint("1. Delete the old volume.")
        self.assertEqual(rep["verdict"], "UNSAFE")
        self.assertIn("HAZARD-NO-WARNING", {f["code"] for f in rep["findings"]})

    def test_late_warning(self):
        self.assertIn("LATE-WARNING", codes("1. Reboot the router.\nWARNING: A reboot drops every call."))

    def test_warning_before_ok(self):
        text = "WARNING: A reboot drops every call.\n1. Reboot the router.\nResult: The light turns green."
        self.assertEqual(sc.lint(text)["verdict"], "READY")

    def test_weak_warning(self):
        self.assertIn("WEAK-WARNING", codes("WARNING: Be careful.\n1. Reboot the router.\nResult: The light is green."))

    def test_no_result_is_note_only(self):
        rep = sc.lint("WARNING: A reboot drops every call.\n1. Reboot the router.")
        self.assertEqual(rep["verdict"], "READY")
        self.assertIn("NO-RESULT", {f["code"] for f in rep["findings"]})


class ChineseRules(unittest.TestCase):
    def test_zh_stacked(self):
        self.assertIn("STACKED", codes("1. 打开页面，然后选择硬盘 2。"))

    def test_zh_passive(self):
        self.assertIn("HIDDEN-ACTOR", codes("1. 密码被工具生成。"))

    def test_zh_hazard(self):
        self.assertEqual(sc.lint("1. 格式化这块硬盘。")["verdict"], "UNSAFE")

    def test_zh_condition_last(self):
        self.assertIn("CONDITION-LAST", codes("1. 关闭工单，如果告警停止了。"))


class CliTests(unittest.TestCase):
    def run_cli(self, *args):
        return subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "stepcheck.py"), *args],
                              capture_output=True, text=True)

    def test_demo_exit_unsafe(self):
        self.assertEqual(self.run_cli("demo").returncode, 2)

    def test_examples(self):
        g = os.path.join(ROOT, "examples", "glossary.json")
        self.assertEqual(self.run_cli("lint", os.path.join(ROOT, "examples", "before.md"), "--glossary", g).returncode, 2)
        self.assertEqual(self.run_cli("lint", os.path.join(ROOT, "examples", "after.md"), "--glossary", g).returncode, 0)
        self.assertEqual(self.run_cli("lint", os.path.join(ROOT, "examples", "after.zh-CN.md"), "--glossary", g).returncode, 0)


if __name__ == "__main__":
    unittest.main()
